#!/bin/bash
# Writes the twelve shot tapes (six shots x two layouts) next to this script. Re-run after editing a shot here
# (render.sh shots runs it first, so a rendered tape always carries the current theme); the .tape files are
# generated, so edit this file, not them.
#   16x9: 1600x900 terminal, Dank Mono 44 px, 14 rows x 60 columns; placed at x=160, y=0 on the 1920x1080 canvas
#   4x5:  1080x1000 terminal, Dank Mono 30 px, 24 rows x 58 columns (padding 30: at 40 only 57 fit, seen in the
#         first render); placed at x=0, y=0 on the 1080x1350 canvas
# Shot list and timings: ../script.md.
#
# Theme: ../theme/clotho-theme.json (Shears / Vermilion, written with the brand kit). VHS takes a theme only inline,
# so it is read here and written into every tape. Until that file exists, the PROVISIONAL theme below is used and
# the tapes say so in their first line: it follows the terminal colour contract (the CLI prints named ANSI only;
# red = Vermilion, used only for the kept timeline, the "keep" marker, the install line and one key number;
# the IRREVERSIBLE badge is reverse video; unchosen timelines are dim; no other hue). Every other ANSI colour maps
# to Paper, so a stray colour code cannot add a hue to the footage.
set -eu
cd "$(dirname "$0")"
THEME_FILE=../theme/clotho-theme.json
PROVISIONAL='{"name":"Shears provisional","black":"#121212","red":"#E2462F","green":"#EDE8DF","yellow":"#EDE8DF","blue":"#EDE8DF","magenta":"#EDE8DF","cyan":"#EDE8DF","white":"#EDE8DF","brightBlack":"#95928D","brightRed":"#E2462F","brightGreen":"#EDE8DF","brightYellow":"#EDE8DF","brightBlue":"#EDE8DF","brightMagenta":"#EDE8DF","brightCyan":"#EDE8DF","brightWhite":"#EDE8DF","background":"#121212","foreground":"#EDE8DF","selection":"#2A2A2A","cursor":"#EDE8DF"}'
if [ -f "$THEME_FILE" ]; then
  THEME=$(python3 -I - "$THEME_FILE" <<'PY'
import json, sys
t = json.load(open(sys.argv[1]))
need = ["background", "foreground", "red", "black", "white", "brightBlack", "cursor"]
miss = [k for k in need if k not in t]
if miss:
    sys.exit(f"theme file lacks {miss}")
if t["background"].upper() != "#121212" or t["red"].upper() not in ("#E2462F",):
    sys.exit(f"theme file: background {t['background']} / red {t['red']} are not Ink #121212 / Vermilion #E2462F")
print(json.dumps(t, separators=(",", ":")))
PY
)
  THEME_NOTE="theme: ../theme/clotho-theme.json"
else
  THEME=$PROVISIONAL
  THEME_NOTE="theme: PROVISIONAL (../theme/clotho-theme.json not found when this tape was made: re-run make_tapes.sh)"
  echo "make_tapes.sh: $THEME_NOTE" >&2
fi

header() { # shot layout title
  local shot=$1 lay=$2 title=$3 fs w h pad
  if [ "$lay" = 16x9 ]; then fs=44 w=1600 h=900 pad=48; else fs=30 w=1080 h=1000 pad=30; fi
  cat <<EOF
# $title ($lay). Generated by make_tapes.sh; see ../script.md for the beat, caption and voiceover.
# $THEME_NOTE
# Needs the variables render.sh exports (CL_TAPES, CL_REPO, CL_HOME, CL_STAGE, CL_TRASH, CL_SINK_PORT, CL_PLUGIN).
Output ${shot}_${lay}.mp4
Set Shell "bash"
Set FontFamily "Dank Mono"
Set FontSize $fs
Set Width $w
Set Height $h
Set Padding $pad
Set LineHeight 1.25
Set Framerate 30
Set TypingSpeed 45ms
Set CursorBlink false
Set Theme $THEME
Hide
Type \`source "\$CL_TAPES/env.sh"\`
Enter
Sleep 600ms
EOF
}

# pg FILE PATTERN N SKIP HOLD [NTH]: one held page of a saved real output (see page() in env.sh)
pg() {
  cat <<EOF
Hide
Type \`page "$1" '$2' $3 $4 ${6:-1}\`
Enter
Sleep 400ms
Show
Sleep $5
Hide
Enter
Sleep 200ms
EOF
}

play() { # cast hold
  cat <<EOF
Type \`clear; asciinema play -q -i 1.0 "\$CL_STAGE/casts/$1"; printf '\\033[?25l\\033[8m%s\\033[0m' cast-done; read -rs _\`
Enter
Show
# the cast ends, then a concealed marker is printed: VHS 0.12.1 Wait+Screen reads the top of the buffer, not
# the scrolled view, so the wait is on the cursor line (tested 2026-11-10)
Wait+Line@240s /cast-done/
Sleep $2
Hide
Enter
EOF
}

for lay in 16x9 4x5; do
  if [ "$lay" = 16x9 ]; then big=0; else big=1; fi
  F="\$CL_STAGE/s4_$lay.ansi"

  # S1 hook: the precious-files block of the demo run rendered in S4 (render S4 first)
  { header s1_hook "$lay" "S1 hook: three timelines, what each would do to the precious files"
    if [ $big = 0 ]; then pg "$F" 'what each timeline would do' 14 1 5s
    else pg "$F" 'what each timeline would do' 15 0 5s; fi
  } > "s1_hook_$lay.tape"

  # S2 the run command of take A (LIVE MODEL at take time; played back here, no model call)
  # DEPENDS ON THE CODE RENAME: the run banner prints names.PRODUCT ("Clotho r-...: ... (nothing will happen for
  # real)" expected, not seen yet); nothing here waits on its wording.
  { header s2_run "$lay" "S2 take A: hermes clotho run, played back from casts/take_a.cast"
    echo 'Type `clear`'; echo 'Enter'; echo 'Sleep 300ms'
    play take_a.cast 3s
  } > "s2_run_$lay.tape"

  # S3 report, untick the delete, Apply, what the sink got, the folder
  { header s3_report_apply "$lay" "S3 report, untick one effect, Apply (no model call)"
    # the take's screen text as well, so it can be searched for names and paths that must not be on screen
    echo "Output s3_report_apply_$lay.txt"
    cat <<'EOF'
Type `restore_take a team-notes && sink_start && cd team-notes && clear`
Enter
Sleep 1.5s
Show
Type `hermes clotho report | less`
Enter
Sleep 5s
Space
Sleep 4s
Space
Sleep 3s
Type "q"
Sleep 300ms
Ctrl+L
Sleep 400ms
# DEPENDS ON TAKE A: @EXCEPT@ is the number of the "delete scratch.tmp" row; render.sh fills it from the ledger
Type `hermes clotho apply --except @EXCEPT@`
Sleep 500ms
Enter
Wait+Line@60s /^[$] *$/
Sleep 3s
Type `sink`
Enter
Sleep 2.5s
Type `ls`
Enter
Sleep 2.5s
Hide
Type `sink_stop`
Enter
Sleep 300ms
EOF
  } > "s3_report_apply_$lay.tape"

  # S4 the fork: the demo command live (recorded model turns, no key), then held pages of that same output
  { header s4_fork "$lay" "S4 hermes clotho demo: a recorded real fork, replayed; comparison and Apply run for real"
    cat <<EOF
Type \`exec > >(tee "$F"); clear\`
Enter
Sleep 600ms
Show
Type \`hermes clotho demo --dir demo\`
Sleep 500ms
Enter
Wait+Line@90s /^[$] *$/
Sleep 1s
Hide
Type \`exec > /dev/tty\`
Enter
Sleep 300ms
EOF
    # The header and fork-table lines print the product name (names.PRODUCT): the patterns match any one-word
    # name, so they hold before and after the code rename. Page lengths were measured on the output before the
    # rename (a longer or shorter name can re-wrap a line): re-check every held page after the rename (script.md,
    # "Lines that depend on output not seen yet").
    if [ $big = 0 ]; then
      pg "$F" '^── [^ ]+ demo ─' 10 0 3s
      pg "$F" '^[^ ]+ fork  f-' 12 0 3s
      pg "$F" '^differences [(]' 13 0 3.5s
      pg "$F" 'what each timeline would do' 14 1 4s
      pg "$F" '── apply claude-sonnet' 8 0 3.5s
      pg "$F" '── the folder afterwards' 6 0 2.5s
    else
      pg "$F" '^── [^ ]+ demo ─' 21 0 4s
      pg "$F" '^[^ ]+ fork  f-' 20 0 3.5s
      pg "$F" '^differences [(]' 23 0 3.5s
      pg "$F" 'what each timeline would do' 15 0 4s
      pg "$F" '── apply claude-sonnet' 18 0 4s
      pg "$F" '── the folder afterwards' 15 0 3s
    fi
  } > "s4_fork_$lay.tape"

  # S5 drift: the same run restored to before Apply, one file edited by hand, Apply stops
  { header s5_drift "$lay" "S5 drift: a file changed by hand stops Apply before any change (no model call)"
    echo "Output s5_drift_$lay.txt"
    cat <<'EOF'
Type `restore_take a team-notes && cd team-notes && clear`
Enter
Sleep 1.5s
Show
Type `echo "- [ ] call the printer guy" >> todo.md`
Enter
Sleep 1.2s
Type `hermes clotho apply`
Sleep 400ms
Enter
# DEPENDS: the wording of the drift line ("changed since the ...") is apply.py/report.py output
Wait+Line@60s /^[$] *$/
Sleep 3s
Type `echo "exit $?"`
Enter
Sleep 2s
EOF
  } > "s5_drift_$lay.tape"

  # S6 cron (LIVE MODEL at take time; played back here). DEPENDS: the roll-up wording is cron.py output after the
  # code rename (not seen yet); nothing here waits on its wording.
  { header s6_cron "$lay" "S6 hermes clotho cron, played back from casts/take_cron.cast"
    echo 'Type `clear`'; echo 'Enter'; echo 'Sleep 300ms'
    play take_cron.cast 3s
  } > "s6_cron_$lay.tape"
done
ls -1 ./*.tape
